import SafariServices
import SwiftUI

/// Terms and privacy acceptance, shown before anything else post-sign-in.
///
/// A policy nobody agreed to is not much use, so acceptance is recorded
/// server-side with the version and a timestamp. The version matters: if the
/// documents change, the app can tell that what this user accepted is no longer
/// what is live, and ask again.
struct ConsentStep: View {
    let onAccepted: () -> Void

    @State private var version: String?
    @State private var submitting = false
    @State private var error: String?
    @State private var sheet: URL?
    /// Defaulted to 30 years ago, not today. A picker sitting on today's date
    /// means the very first drag reads as "born this year", and it also nudges
    /// nobody toward a particular answer.
    @State private var birthDate = Calendar.current.date(
        byAdding: .year, value: -30, to: Date()
    ) ?? Date()
    @State private var enteredBirthDate = false

    private var base: String { APIClient.shared.baseURL.absoluteString }

    var body: some View {
        ScreenBackground {
            VStack(alignment: .leading, spacing: 0) {
                Spacer(minLength: 20)

                Text("Before we start")
                    .font(.system(size: 28, weight: .black))
                    .tracking(-0.4)
                    .foregroundStyle(Theme.Palette.text)

                ScrollView {
                    VStack(alignment: .leading, spacing: 18) {
                        Panel(accent: Theme.Palette.caution) {
                            VStack(alignment: .leading, spacing: 10) {
                                SectionLabel("This is not medical advice")
                                Text("Coach Will gives general training guidance "
                                     + "generated by software. It isn't a doctor and "
                                     + "it can be wrong.")
                                    .font(Theme.Font.body)
                                    .foregroundStyle(Theme.Palette.text)
                                Text("Talk to a physician before starting or changing "
                                     + "a training programme. Stop and get medical help "
                                     + "if you feel chest pain, faint, or anything you "
                                     + "think is serious — don't wait for the app to "
                                     + "tell you.")
                                    .font(Theme.Font.body)
                                    .foregroundStyle(Theme.Palette.textDim)
                            }
                        }

                        Panel {
                            VStack(alignment: .leading, spacing: 10) {
                                SectionLabel("Your data")
                                Text("We read your health data to write your brief. "
                                     + "We never sell it, never use it for advertising, "
                                     + "and never write back to Apple Health.")
                                    .font(Theme.Font.body)
                                    .foregroundStyle(Theme.Palette.textDim)
                                Text("You can delete your account, and everything in "
                                     + "it, at any time from the Goal tab.")
                                    .font(Theme.Font.body)
                                    .foregroundStyle(Theme.Palette.textDim)
                            }
                        }

                        agePanel

                        VStack(spacing: 8) {
                            documentLink("Terms of Use", path: "/legal/terms")
                            documentLink("Privacy Policy", path: "/legal/privacy")
                        }

                        if let error {
                            Text(error)
                                .font(Theme.Font.caption)
                                .foregroundStyle(Theme.Palette.bad)
                        }
                    }
                    .padding(.top, 20)
                }
                .scrollIndicators(.hidden)

                ActionButton(title: submitting ? "One moment" : "I agree") {
                    Task { await accept() }
                }
                .disabled(!canAccept)
                .opacity(canAccept ? 1 : 0.6)
                .padding(.top, 12)

                Text("Tapping I agree records that you accepted both documents.")
                    .font(.system(size: 12))
                    .foregroundStyle(Theme.Palette.textDim)
                    .frame(maxWidth: .infinity, alignment: .center)
                    .padding(.top, 10)
                    .padding(.bottom, 20)
            }
            .padding(.horizontal, Theme.Metric.gutter)
        }
        .task { await loadVersion() }
        .sheet(item: $sheet) { url in SafariView(url: url) }
    }

    /// Date of birth, required by the terms' 16+ rule.
    ///
    /// A picker rather than a "I am 16 or over" checkbox: a checkbox records
    /// only that somebody tapped a button, which is worth very little if the
    /// question is ever actually asked.
    private var agePanel: some View {
        Panel(accent: enteredBirthDate && !isOldEnough ? Theme.Palette.bad : nil) {
            VStack(alignment: .leading, spacing: 12) {
                SectionLabel("Date of birth")
                DatePicker(
                    "",
                    selection: Binding(
                        get: { birthDate },
                        set: { birthDate = $0; enteredBirthDate = true }
                    ),
                    in: ...Date(),
                    displayedComponents: .date
                )
                .datePickerStyle(.compact)
                .labelsHidden()
                .tint(Theme.Palette.accent)
                .frame(maxWidth: .infinity, alignment: .leading)

                if enteredBirthDate && !isOldEnough {
                    Text("Coach Will is for people 16 and over.")
                        .font(Theme.Font.caption)
                        .foregroundStyle(Theme.Palette.bad)
                } else {
                    Text("Coach Will handles health data, so it's for 16 and over. "
                         + "We use this only to check that.")
                        .font(.system(size: 12))
                        .foregroundStyle(Theme.Palette.textDim)
                        .fixedSize(horizontal: false, vertical: true)
                }
            }
        }
    }

    private var isOldEnough: Bool {
        let years = Calendar.current.dateComponents(
            [.year], from: birthDate, to: Date()
        ).year ?? 0
        return years >= 16
    }

    /// Requires an explicit interaction with the picker. Without that flag the
    /// default of 30 years ago would silently count as an answer nobody gave.
    private var canAccept: Bool {
        !submitting && version != nil && enteredBirthDate && isOldEnough
    }

    private func documentLink(_ title: String, path: String) -> some View {
        Button {
            sheet = URL(string: base + path)
        } label: {
            HStack {
                Text(title)
                    .font(Theme.Font.bodyStrong)
                    .foregroundStyle(Theme.Palette.text)
                Spacer()
                Text("Read →")
                    .font(Theme.Font.caption)
                    .foregroundStyle(Theme.Palette.accent)
            }
            .padding(16)
            .background(Theme.Palette.surface)
            .overlay(Rectangle().stroke(Theme.Palette.line, lineWidth: 1))
            .clipShape(RoundedRectangle(cornerRadius: Theme.Metric.radius))
        }
        .buttonStyle(PressStyle())
    }

    private func loadVersion() async {
        // The version comes from the server rather than being compiled in, so a
        // document change doesn't need an app release to take effect.
        struct Status: Decodable { let currentVersion: String; let upToDate: Bool }
        do {
            let status: Status = try await APIClient.shared.get("/v1/me/consent")
            if status.upToDate {
                onAccepted()
            } else {
                version = status.currentVersion
            }
        } catch {
            self.error = "Couldn't load the current terms. \(error.localizedDescription)"
        }
    }

    private func accept() async {
        guard let version else { return }
        submitting = true
        defer { submitting = false }
        do {
            struct Empty: Decodable {}
            let _: Empty = try await APIClient.shared.post(
                "/v1/me/consent",
                body: ["version": version, "date_of_birth": CalendarDate.localString(from: birthDate)]
            )
            onAccepted()
        } catch {
            self.error = error.localizedDescription
        }
    }
}

/// In-app browser. Opening Safari would drop the user out of the app mid-signup,
/// and they may not come back.
struct SafariView: UIViewControllerRepresentable {
    let url: URL
    func makeUIViewController(context: Context) -> SFSafariViewController {
        SFSafariViewController(url: url)
    }
    func updateUIViewController(_ vc: SFSafariViewController, context: Context) {}
}

extension URL: @retroactive Identifiable {
    public var id: String { absoluteString }
}
